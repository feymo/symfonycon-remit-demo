#!/bin/sh
# Generates Remit.xcodeproj for this Mac and opens it.
#   REMIT_TEAM_ID=ABCDE12345 ./generate.sh     (your Apple team ID, to run on the iPhone)
set -e
cd "$(dirname "$0")"

command -v xcodegen >/dev/null 2>&1 || { echo "XcodeGen is missing: brew install xcodegen"; exit 1; }

HOST="$(scutil --get LocalHostName | tr '[:upper:]' '[:lower:]').local"   # lowercase: see Server.swift
{
    echo "// Generated by generate.sh — not committed."
    echo "REMIT_SERVER_HOST = $HOST"
    if [ -n "${REMIT_TEAM_ID:-}" ]; then echo "REMIT_TEAM_ID = $REMIT_TEAM_ID"; fi
} > Config/Local.xcconfig

xcodegen generate --quiet
echo "iPhone → http://$HOST   ·   Simulator → http://localhost"
open Remit.xcodeproj
